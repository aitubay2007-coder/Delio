test("the name field stays readable when focused", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto("/s/primer")
  await page.getByRole("button", { name: "В корзину" }).first().click()
  await page.getByRole("button", { name: "Открыть корзину" }).click()
  await page.getByRole("button", { name: "Оформить" }).click()
  const input = page.getByLabel("Ваше имя")
  await input.focus()
  const font = await input.evaluate((element) => getComputedStyle(element).fontSize)
  expect(Number.parseFloat(font)).toBeGreaterThanOrEqual(16)
  const box = await input.boundingBox()
  expect(box).not.toBeNull()
  expect(box!.y).toBeGreaterThan(0)
  expect(box!.y + box!.height).toBeLessThan(844)
})

for (const width of [320, 390, 430]) {
  test(`storefront fits ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 800 })
    await page.goto("/s/primer")
    await expect(page.getByRole("heading", { name: "Букеты" })).toBeVisible()
    await expect(page.getByText("Коробка с цветами и длинной атласной лентой")).toBeVisible()
    const cards = page.locator("[data-slot=product-card]")
    const boxes = await cards.evaluateAll((nodes) =>
      nodes.slice(0, 2).map((node) => {
        const rect = node.getBoundingClientRect()
        return { x: rect.x, y: rect.y }
      }),
    )
    if (width >= 360) expect(Math.abs(boxes[0].y - boxes[1].y)).toBeLessThan(12)
    else expect(boxes[1].y).toBeGreaterThan(boxes[0].y + 40)
    const overflow = await page.evaluate(
      () => document.documentElement.scrollWidth <= document.documentElement.clientWidth + 1,
    )
    expect(overflow).toBe(true)
  })
}
